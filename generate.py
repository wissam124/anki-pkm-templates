#!/usr/bin/env python3
"""Generate the copy-ready PKM SJ Anki templates and styles."""

from __future__ import annotations

import argparse
import difflib
import hashlib
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "src"

TEMPLATES = {
    "pkm-sj-basic-front.html": "basic-front.html",
    "pkm-sj-basic-back.html": "basic-back.html",
    "pkm-sj-cloze-front.html": "cloze-front.html",
    "pkm-sj-cloze-back.html": "cloze-back.html",
    "pkm-sj-math-front.html": "math-front.html",
    "pkm-sj-math-back.html": "math-back.html",
    "pkm-sj-programming-front.html": "programming-front.html",
    "pkm-sj-programming-back.html": "programming-back.html",
}

THEMES = ("minimal", "solarized", "nord")
VARIANTS = ("basic", "cloze", "math", "programming")
OUTPUT_DIRECTORIES = (ROOT / "templates", ROOT / "styles" / "css")
GENERATED_MARKER = "Generated by generate.py; edit src instead."


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").rstrip() + "\n"


def build_id() -> str:
    """Return a short fingerprint shared by every artifact in this build."""
    digest = hashlib.sha256()
    inputs = [Path(__file__), *sorted(SOURCE.rglob("*"))]
    for path in inputs:
        if path.is_file():
            digest.update(path.relative_to(ROOT).as_posix().encode("utf-8"))
            digest.update(path.read_bytes())
    return digest.hexdigest()[:12]


def outputs() -> dict[Path, str]:
    script = read(SOURCE / "templates" / "enhance.html").rstrip()
    fingerprint = build_id()
    generated: dict[Path, str] = {}

    for output_name, source_name in TEMPLATES.items():
        source = read(SOURCE / "templates" / source_name)
        if source.count("<!-- @enhance -->") != 1:
            raise ValueError(f"{source_name}: expected exactly one enhancement placeholder")
        header = (
            f"<!-- PKM SJ artifact: {output_name}; build: {fingerprint}; "
            f"{GENERATED_MARKER} -->\n"
        )
        generated[ROOT / "templates" / output_name] = header + source.replace(
            "<!-- @enhance -->", script
        )

    base = read(SOURCE / "styles" / "base.css")
    for variant in VARIANTS:
        for theme in THEMES:
            output_name = f"pkm-sj-{variant}-{theme}.css"
            parts = [
                (
                    f"/* PKM SJ artifact: {output_name}; build: {fingerprint}; "
                    f"{GENERATED_MARKER} */\n"
                ),
                base,
                read(SOURCE / "styles" / "themes" / f"{theme}.css"),
                read(SOURCE / "styles" / "variants" / f"{variant}.css"),
            ]
            generated[ROOT / "styles" / "css" / output_name] = "\n".join(parts)

    return generated


def validate(generated: dict[Path, str]) -> list[str]:
    errors = []
    for path, content in generated.items():
        if path.suffix == ".html":
            if f"PKM SJ artifact: {path.name}" not in content:
                errors.append(f"{path}: missing artifact identity")
            if "<!-- @enhance -->" in content:
                errors.append(f"{path}: unresolved enhancement placeholder")
            if content.count("<script>") != 1:
                errors.append(f"{path}: expected exactly one enhancement script")
            if ":scope" in content or ".innerHTML" in content:
                errors.append(f"{path}: unsafe or incompatible DOM construction remains")
            sections = re.findall(r"{{([#/])([^{}]+)}}", content)
            stack: list[str] = []
            for marker, name in sections:
                if marker == "#":
                    stack.append(name)
                elif not stack or stack.pop() != name:
                    errors.append(f"{path}: mismatched Anki conditional {name}")
                    break
            if stack:
                errors.append(f"{path}: unclosed Anki conditional {stack[-1]}")
            orders = re.findall(r'data-prettify-order="([^"]+)"', content)
            if any(not order.isdigit() for order in orders):
                errors.append(f"{path}: non-numeric data-prettify-order")
            if len(orders) != len(set(orders)):
                errors.append(f"{path}: duplicate data-prettify-order")
            for required in ("prettify-flashcard", "prettify-deck", "prettify-field--front"):
                if required not in content:
                    errors.append(f"{path}: missing {required}")
            if path.name.endswith("-back.html") and "prettify-divider" not in content:
                errors.append(f"{path}: missing answer divider")
            if "cloze" in path.name and "{{edit:cloze:Text}}" not in content:
                errors.append(f"{path}: missing editable cloze field")
        elif path.suffix == ".css":
            if f"PKM SJ artifact: {path.name}" not in content:
                errors.append(f"{path}: missing artifact identity")
            for required in (".card.night_mode", ".card.nightMode", "img.latex"):
                if required not in content:
                    errors.append(f"{path}: missing {required}")
            if ".woff" in content or "@font-face" in content:
                errors.append(f"{path}: external font media reference is not allowed")
            if "-cloze-" in path.name and "\n  order:" in content:
                errors.append(f"{path}: cloze layout must use DOM order")
    return errors


def is_managed_output(path: Path) -> bool:
    """Return whether PATH identifies itself as generator-owned."""
    try:
        return GENERATED_MARKER in path.read_text(encoding="utf-8")[:512]
    except (OSError, UnicodeError):
        return False


def check(generated: dict[Path, str]) -> int:
    stale = []
    for path, expected in generated.items():
        actual = path.read_text(encoding="utf-8") if path.exists() else ""
        if actual != expected:
            stale.append(path)
            diff = difflib.unified_diff(
                actual.splitlines(),
                expected.splitlines(),
                fromfile=str(path),
                tofile=f"generated:{path}",
                lineterm="",
            )
            print("\n".join(list(diff)[:40]))
    unexpected = sorted(
        path
        for directory in OUTPUT_DIRECTORIES
        for path in directory.glob("*")
        if path.is_file() and path not in generated and is_managed_output(path)
    )
    for path in unexpected:
        print(f"Unexpected generated file: {path}")
    errors = validate(generated)
    for error in errors:
        print(error)
    if stale or unexpected or errors:
        print(f"Generation check failed; run ./generate.py")
        return 1
    print(f"All {len(generated)} generated files are up to date and valid.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="check outputs without changing files"
    )
    args = parser.parse_args()
    generated = outputs()

    if args.check:
        return check(generated)

    for directory in OUTPUT_DIRECTORIES:
        directory.mkdir(parents=True, exist_ok=True)
        for path in directory.glob("*"):
            if path.is_file() and path not in generated and is_managed_output(path):
                path.unlink()
                print(f"removed {path.relative_to(ROOT)}")

    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(path.relative_to(ROOT))
    errors = validate(generated)
    if errors:
        print("\n".join(errors))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
